#!/usr/bin/env node
// @ts-check
/**
 * Vendors the language-neutral CLDR JSON artifacts from a sibling lokalized-java
 * checkout into this repository, and verifies a checked-in snapshot against it.
 *
 * This mirrors lokalized.com/scripts/java-snapshot.js deliberately: same manifest
 * shape, same aggregate-digest construction, same sibling-directory resolution.
 * CI reconstructs the sibling layout with actions/checkout `path:`; see README.
 *
 *   node scripts/java-snapshot.mjs --write   regenerate the snapshot from the sibling
 *   node scripts/java-snapshot.mjs --check   verify the checked-in snapshot (exit 1 on drift)
 */
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const specDirectory = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const javaDirectory = process.env.LOKALIZED_JAVA_DIR
  ? resolve(process.env.LOKALIZED_JAVA_DIR)
  : resolve(specDirectory, "../lokalized-java");

const REPOSITORY = "lokalized/lokalized-java";
const MANIFEST_PATH = join(specDirectory, "vendor/lokalized-java/snapshot.json");

/**
 * The vendored set. Every entry is generated by CldrDataGenerator from SHA-pinned
 * CLDR inputs; all three are CLDR-derived and therefore Unicode-3.0.
 */
const SOURCE_PATHS = [
  "src/build/resources/cldr/cldr-plural-data.json",
  "src/build/resources/cldr/cldr-locale-data.json",
  "src/build/resources/cldr/cldr-conformance-vectors.json",
];

const LICENSE = "Unicode-3.0";

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

/** Aggregate digest over the manifest's own fields, matching lokalized.com exactly. */
function inputsDigestFor(files) {
  const digest = createHash("sha256");
  for (const file of files) {
    digest.update(file.sourcePath);
    digest.update("\0");
    digest.update(file.snapshotPath);
    digest.update("\0");
    digest.update(String(file.byteLength));
    digest.update("\0");
    digest.update(file.sha256);
    digest.update("\0");
    digest.update(file.license);
    digest.update("\n");
  }
  return `sha256:${digest.digest("hex")}`;
}

async function gitCommit() {
  const { spawnSync } = await import("node:child_process");
  const result = spawnSync("git", ["-C", javaDirectory, "rev-parse", "HEAD"], { encoding: "utf8" });
  if (result.status !== 0) return null;
  const head = result.stdout.trim();
  const dirty = spawnSync("git", ["-C", javaDirectory, "status", "--porcelain", "--", ...SOURCE_PATHS], {
    encoding: "utf8",
  });
  // A commit only pins the bytes if those bytes are actually committed. Recording a
  // HEAD that does not contain them would be worse than recording none.
  if (dirty.status === 0 && dirty.stdout.trim().length > 0) return null;
  return /^[0-9a-f]{40}$/.test(head) ? head : null;
}

async function buildManifest() {
  const files = [];
  for (const sourcePath of SOURCE_PATHS) {
    const bytes = await readFile(join(javaDirectory, sourcePath));
    files.push({
      sourcePath,
      snapshotPath: `vendor/lokalized-java/${sourcePath}`,
      byteLength: bytes.byteLength,
      sha256: `sha256:${sha256(bytes)}`,
      license: LICENSE,
    });
  }
  return {
    formatVersion: 1,
    repository: REPOSITORY,
    commit: await gitCommit(),
    inputsSha256: inputsDigestFor(files),
    files,
  };
}

async function write() {
  const manifest = await buildManifest();
  for (const file of manifest.files) {
    const destination = join(specDirectory, file.snapshotPath);
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, await readFile(join(javaDirectory, file.sourcePath)));
  }
  await mkdir(dirname(MANIFEST_PATH), { recursive: true });
  await writeFile(MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(
    JSON.stringify({
      status: "written",
      commit: manifest.commit,
      inputsSha256: manifest.inputsSha256,
      files: manifest.files.length,
    }),
  );
}

async function check() {
  const problems = [];
  /** @type {any} */
  let manifest;
  try {
    manifest = JSON.parse(await readFile(MANIFEST_PATH, "utf8"));
  } catch {
    console.error("snapshot manifest is missing or unreadable; run --write");
    process.exit(1);
  }

  if (manifest.inputsSha256 !== inputsDigestFor(manifest.files))
    problems.push("inputsSha256 does not describe the manifest's own file list");

  for (const file of manifest.files) {
    let bytes;
    try {
      bytes = await readFile(join(specDirectory, file.snapshotPath));
    } catch {
      problems.push(`missing vendored file: ${file.snapshotPath}`);
      continue;
    }
    if (bytes.byteLength !== file.byteLength)
      problems.push(`${file.snapshotPath}: byteLength ${bytes.byteLength} != ${file.byteLength}`);
    if (`sha256:${sha256(bytes)}` !== file.sha256)
      problems.push(`${file.snapshotPath}: sha256 mismatch against the manifest`);

    // When the sibling checkout is present, also prove the snapshot still matches upstream.
    try {
      const upstream = await readFile(join(javaDirectory, file.sourcePath));
      if (`sha256:${sha256(upstream)}` !== file.sha256)
        problems.push(`${file.sourcePath}: sibling lokalized-java has drifted from the snapshot`);
    } catch {
      // Sibling absent. The snapshot is still self-verifying; note it and continue.
    }
  }

  if (problems.length > 0) {
    console.error(JSON.stringify({ status: "drift", problems }, null, 2));
    process.exit(1);
  }
  console.log(
    JSON.stringify({ status: "current", commit: manifest.commit, files: manifest.files.length }),
  );
}

const mode = process.argv.includes("--write") ? "write" : process.argv.includes("--check") ? "check" : null;
if (!mode) {
  console.error("usage: node scripts/java-snapshot.mjs --write | --check");
  process.exit(2);
}
await (mode === "write" ? write() : check());
